HARAKAT = set("ًٌٍَُِّْ")
SUKUN = "ْ"


def split_marks(vocal):
    """[(letter, marks)] from a vocalised spelling."""
    seq = []
    for ch in vocal:
        if ch in HARAKAT and seq:
            seq[-1][1] += ch
        else:
            seq.append([ch, ""])
    return seq


def vocalise(form, text, keep=None, drop_sukun=True):
    """Insert text's harakat into form (which may contain tatweel).

    keep: optional set of letter indices whose harakat are kept (others dropped).
    """
    v = VOCAL.get(text)
    if not v:
        return form
    seq = split_marks(v)
    out, j = "", 0
    for ch in form:
        if ch == "ـ":
            out += ch
            continue
        while j < len(seq) and seq[j][0] != ch:
            j += 1
        if j >= len(seq):
            return form
        m = seq[j][1]
        if drop_sukun:
            m = m.replace(SUKUN, "")
        if keep is not None and j not in keep:
            m = ""
        out += ch + m
        j += 1
    return out


def marked_letters(text, drop_sukun=True):
    v = VOCAL.get(text)
    if not v:
        return []
    seq = split_marks(v)
    return [i for i, (c, m) in enumerate(seq) if (m.replace(SUKUN, "") if drop_sukun else m)]
